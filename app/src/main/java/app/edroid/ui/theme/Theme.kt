/**
 * Material 3 Expressive theme: dynamic (Material You) colors when the OS provides them, the
 * expressive motion scheme for springy transitions, and the rounder expressive shape scale.
 */
@Composable
fun EDroidTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    // Layering convention for this app (see Layering.kt):
    // screens sit on surfaceContainer, list items on surfaceContainerHighest, and the selected
    // nav pill on background.
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialExpressiveTheme(
        colorScheme = colorScheme,
        motionScheme = MotionScheme.expressive(),
        shapes = Shapes(),
        typography = EDroidTypography,
    ) {
        // Pages are drawn on plain backgrounds rather than a Surface, so nothing else sets a content
        // color: text straight on a page would fall back to black, unreadable in dark theme.
        CompositionLocalProvider(LocalContentColor provides colorScheme.onSurface, content = content)
    }
}
